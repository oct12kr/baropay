function assertNoLeak(value) {
  if (typeof value === "string" && value.includes(WORDPRESS_APP_PASSWORD)) {
    throw new Error("refusing to log a string containing the app password");
  }
}

async function main() {
  if (!WORDPRESS_URL) {
    console.error("WORDPRESS_URL이 설정되어 있지 않습니다. .env.local을 확인해주세요.");
    process.exitCode = 1;
    return;
  }

  if (!WORDPRESS_USERNAME || !WORDPRESS_APP_PASSWORD) {
    console.error(
      "WORDPRESS_USERNAME 또는 WORDPRESS_APP_PASSWORD가 비어 있습니다. " +
        "임의의 값을 생성하지 않으므로 발행을 진행하지 않습니다."
    );
    process.exitCode = 1;
    return;
  }

  const apiBase = `${WORDPRESS_URL}/wp-json/wp/v2`;
  const authHeader = `Basic ${Buffer.from(`${WORDPRESS_USERNAME}:${WORDPRESS_APP_PASSWORD}`).toString("base64")}`;

  console.log(`WordPress 연결 대상: ${WORDPRESS_URL}`);

  const existingRes = await fetch(`${apiBase}/posts?per_page=100&status=publish,draft,pending`, {
    headers: { Authorization: authHeader },
  });

  if (!existingRes.ok) {
    console.error(`기존 글 목록을 가져오지 못했습니다. HTTP ${existingRes.status}`);
    process.exitCode = 1;
    return;
  }

  const existingPosts = await existingRes.json();
  const existingTitles = new Set(
    existingPosts.map((post) => post.title.rendered.trim().toLowerCase())
  );

  let created = 0;
  let skipped = 0;
  let failed = 0;

  for (const post of POSTS) {
    if (existingTitles.has(post.title.trim().toLowerCase())) {
      console.log(`건너뜀 (이미 존재): ${post.title}`);
      skipped += 1;
      continue;
    }

    const res = await fetch(`${apiBase}/posts`, {
      method: "POST",
      headers: {
        Authorization: authHeader,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        title: post.title,
        content: post.content,
        status: "publish",
      }),
    });

    if (res.status === 401 || res.status === 403) {
      console.error(`인증/권한 오류 (HTTP ${res.status})로 발행을 중단합니다: ${post.title}`);
      failed += 1;
      break;
    }

    if (!res.ok) {
      const body = await res.text();
      assertNoLeak(body);
      console.error(`발행 실패 (HTTP ${res.status}): ${post.title}`);
      failed += 1;
      continue;
    }

    const created_post = await res.json();
    console.log(`발행 완료: ${post.title} (slug: ${created_post.slug})`);
    created += 1;
  }

  console.log(`\n결과 — 발행 ${created}건 / 건너뜀 ${skipped}건 / 실패 ${failed}건`);
}

main().catch((error) => {
  console.error("스크립트 실행 중 오류가 발생했습니다:", error.message);
  process.exitCode = 1;
});
